layer print_graph(Node* n) {
  layer current;
  current._idx = n->_idx;
  current.op = opco(n->Opcode());
  for(uint i = 0; i < n->len(); i++) {
    Node* p = n->in(i);
    if(p != nullptr)
    current.parent[i] = opco(p->Opcode());
  } 
 
  for(uint i = 0; i < n->outcnt(); i++) {
    Node* c = n->raw_out(i);
    if(c != nullptr)
    current.child[i] = opco(c->Opcode()); 
  }
  return current;
} 
 
